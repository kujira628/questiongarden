let current = 'ja';
export function setLang(l) { current = STRINGS[l] ? l : 'ja'; document.documentElement.lang = current; }
export function getLang() { return current; }
export function t(key, vars) {
  let s = (STRINGS[current] && STRINGS[current][key]) ?? STRINGS.en[key] ?? key;
  if (vars) for (const k in vars) s = s.replace('{' + k + '}', vars[k]);
  return s;
}
export function fmtDate(ts, withTime = true) {
  const loc = current === 'ja' ? 'ja-JP' : 'en-US';
  const o = withTime ? { month: 'short', day: 'numeric', hour: '2-digit', minute: '2-digit' } : { year: 'numeric', month: 'short', day: 'numeric' };
  return new Intl.DateTimeFormat(loc, o).format(new Date(ts));
}
